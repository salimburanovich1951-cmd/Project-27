def qoshish(a, b):
    return a + b
def ayirish(a, b):
    return a - b
def kopaytirish(a,b):
    return a * b
def bolish(a,b):
    return a/b
def juft_yoki_toq(son):
    if son % 2 == 0:
        return f"{son} - Juft son"
    else:
        return f"{son} - Toq son"
def matnni_katta_qil(matn):
    return matn.upper()
